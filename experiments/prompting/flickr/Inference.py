#!/usr/bin/env python3
"""
Flickr30k Inference Script

This script runs inference on a vision-language model for the Flickr30k dataset.
It generates captions for images, measures inference metrics, and saves results
to a JSON file. Supports both local models and HuggingFace-hosted models.
"""

import argparse
import json
import time
import threading
import torch
from typing import List, Dict, Tuple
from PIL import Image as PILImage
from datasets import load_from_disk
from unsloth import FastVisionModel
from transformers import TextIteratorStreamer
import re
from io import BytesIO


# ---------------------------------------------------------------------
# Utility Functions
# ---------------------------------------------------------------------

def clean_text_output(raw_output: str) -> str:
    """
    Clean raw model output by removing code blocks, markdown, and extra text.
    Only keeps the main caption string.

    Args:
        raw_output (str): Raw text generated by the model

    Returns:
        str: Cleaned caption string
    """
    cleaned = re.sub(r'```.*?```', '', raw_output, flags=re.DOTALL)
    return cleaned.strip()


# ---------------------------------------------------------------------
# Single Image Inference
# ---------------------------------------------------------------------

def run_inference(
    image: PILImage.Image,
    model,
    tokenizer,
    prompt: str,
    max_new_tokens: int = 256
) -> Tuple[str, float, float]:
    """
    Run inference on a single image using the vision-language model.

    Args:
        image (PILImage.Image): Input image
        model: Loaded FastVisionModel
        tokenizer: Model tokenizer
        prompt (str): Prompt text to guide caption generation
        max_new_tokens (int): Maximum number of tokens to generate

    Returns:
        Tuple[str, float, float]: (caption, inference_time_s, peak_vram_mb)
    """
    try:
        # Build input for the model
        messages = [
            {
                "role": "user",
                "content": [
                    {"type": "image"},        # Embed the image in input
                    {"type": "text", "text": prompt}  # Include the prompt
                ]
            }
        ]
        input_text = tokenizer.apply_chat_template(messages, add_generation_prompt=True)

        # Tokenize and move to GPU
        inputs = tokenizer(image, input_text, add_special_tokens=False, return_tensors="pt").to("cuda")
        inputs.pop("token_type_ids", None)  # Remove unused keys for compatibility

        # Reset peak GPU memory stats
        torch.cuda.reset_peak_memory_stats("cuda")
        t_start = time.time()

        # Streaming output for real-time decoding
        streamer = TextIteratorStreamer(tokenizer, skip_prompt=True, skip_special_tokens=True)
        thread = threading.Thread(
            target=model.generate,
            kwargs={
                **inputs,
                "streamer": streamer,
                "max_new_tokens": max_new_tokens,
                "use_cache": True,
                "do_sample": False,  # Greedy decoding
                "top_p": 1.0,
                "top_k": 0,
            },
        )
        thread.start()

        # Collect tokens as they are generated
        generated_text = ""
        for token in streamer:
            generated_text += token

        thread.join()
        t_end = time.time()

        # Measure inference metrics
        inference_time_s = t_end - t_start
        peak_vram_mb = torch.cuda.max_memory_allocated("cuda") / (1024 ** 2)

        # Clean the generated text
        cleaned_caption = clean_text_output(generated_text)
        return cleaned_caption, inference_time_s, peak_vram_mb

    except Exception as e:
        print(f"❌ Error during inference: {e}")
        return "", 0.0, 0.0


# ---------------------------------------------------------------------
# Warmup Function
# ---------------------------------------------------------------------

def run_warmup(
    model,
    tokenizer,
    num_warmup: int = 2
):
    """
    Run warmup inference to initialize CUDA kernels and stabilize timing.

    Args:
        model: Vision-language model
        tokenizer: Tokenizer
        num_warmup: Number of warmup iterations
    """
    print(f"\n🔥 Running {num_warmup} warmup inference(s) to initialize CUDA kernels...")

    # Create a small dummy image for warmup
    dummy_image = PILImage.new('RGB', (224, 224), color='white')
    warmup_prompt = "Describe this image briefly."

    for i in range(num_warmup):
        print(f"   Warmup {i+1}/{num_warmup}...", end=" ", flush=True)
        _, warmup_time, _ = run_inference(
            dummy_image,
            model,
            tokenizer,
            warmup_prompt,
            max_new_tokens=32,  # Short output for faster warmup
        )
        print(f"done ({warmup_time:.2f}s)")

    # Clear CUDA cache after warmup
    torch.cuda.empty_cache()
    torch.cuda.reset_peak_memory_stats()
    print("✅ Warmup complete! CUDA kernels initialized.\n")


# ---------------------------------------------------------------------
# Load Model
# ---------------------------------------------------------------------

def load_model(
    model_path: str,
    load_from_hf: bool = False,
    base_model: str = "unsloth/gemma-3-12b-it"
):
    """
    Load FastVisionModel from local directory or HuggingFace.

    Args:
        model_path (str): Path to local model or HuggingFace adapter
        load_from_hf (bool): If True, load base model from HF and apply adapter
        base_model (str): Base model name for HF loading

    Returns:
        Tuple[model, tokenizer]
    """
    if load_from_hf:
        print(f"🔄 Loading base model from HuggingFace: {base_model}")
        model, tokenizer = FastVisionModel.from_pretrained(
            base_model,
            load_in_4bit=True,
            use_gradient_checkpointing="unsloth",
        )
        print(f"🔄 Applying adapter from: {model_path}")
        model.load_adapter(model_path)
    else:
        print(f"🔄 Loading full model from local path: {model_path}")
        model, tokenizer = FastVisionModel.from_pretrained(
            model_path,
            load_in_4bit=True,
            use_gradient_checkpointing="unsloth",
        )

    model.eval()
    print("✅ Model loaded successfully.")
    return model, tokenizer


# ---------------------------------------------------------------------
# Batch Inference
# ---------------------------------------------------------------------

def run_inference_batch(
    model,
    tokenizer,
    test_dataset,
    prompt: str,
    sample_indices: List[int],
    max_new_tokens: int = 256,
    skip_warmup: bool = False
) -> Tuple[Dict[int, str], Dict[int, List[str]], Dict[int, float], Dict[int, float]]:
    """
    Run inference for multiple images in a batch.

    Args:
        model: Loaded FastVisionModel
        tokenizer: Model tokenizer
        test_dataset: Flickr30k dataset loaded with datasets.load_from_disk
        prompt (str): Prompt for captioning
        sample_indices (List[int]): Indices of samples to process
        max_new_tokens (int): Maximum tokens to generate per image
        skip_warmup (bool): Skip warmup inference (default: False)

    Returns:
        Tuple[Dict[int, str], Dict[int, List[str]], Dict[int, float], Dict[int, float]]:
            predictions, ground_truths, inference_times, vram_usage
    """
    # Run warmup to initialize CUDA kernels (avoids inflated first inference time)
    if not skip_warmup:
        run_warmup(model, tokenizer, num_warmup=2)

    predictions: Dict[int, str] = {}
    ground_truths: Dict[int, List[str]] = {}
    inference_times: Dict[int, float] = {}
    vram_usage: Dict[int, float] = {}

    print(f"🚀 Running inference on {len(sample_indices)} samples...")
    print(f"   Using greedy decoding (deterministic)")

    for idx in sample_indices:
        print(f"\n📦 Processing sample {idx}...")
        sample = test_dataset[idx]

        # Load PIL image from bytes if necessary
        if isinstance(sample["image"], bytes):
            image = PILImage.open(BytesIO(sample["image"]))
        else:
            image = sample["image"]

        # Run single-image inference
        pred, inf_time, vram = run_inference(image, model, tokenizer, prompt, max_new_tokens)
        predictions[idx] = pred

        # ✅ Store metrics so evaluate.py can read them
        inference_times[idx] = float(inf_time)
        vram_usage[idx] = float(vram)

        # Save ground truth captions (Flickr30k has list of 5 refs)
        captions = sample.get("caption", [])
        if isinstance(captions, list):
            refs = [str(c) for c in captions]
        else:
            refs = [str(captions)]

        ground_truths[idx] = refs

        # Print metrics for current sample
        print(f"   ⏱️  Inference time: {inf_time:.3f}s")
        print(f"   💾 VRAM usage: {vram:.2f} MB")
        print(f"   📝 Prediction: {pred[:100]}...")

    print("\n✅ Inference batch complete!")

    # Force cleanup to prevent CUDA issues in long-running loops
    import gc
    gc.collect()
    if torch.cuda.is_available():
        torch.cuda.empty_cache()
        torch.cuda.synchronize()

    return predictions, ground_truths, inference_times, vram_usage


# ---------------------------------------------------------------------
# Main Script
# ---------------------------------------------------------------------

if __name__ == "__main__":
    parser = argparse.ArgumentParser(description="Flickr30k Inference Script")

    # Model arguments
    parser.add_argument("--model-path", type=str, required=True, help="Path to local model or adapter")
    parser.add_argument("--load-from-hf", action="store_true", help="Load base model from HF and apply adapter")
    parser.add_argument("--base-model", type=str, default="unsloth/gemma-3-12b-it", help="Base model name for HF loading")

    # Dataset arguments
    parser.add_argument("--test-dataset", type=str, default="./flickr30k_splits/test", help="Path to Flickr30k test dataset")
    parser.add_argument("--prompt", type=str, required=True, help="Prompt text for caption generation")
    parser.add_argument("--sample-indices", type=str, default="", help="Comma-separated indices of samples to process")

    # Inference arguments
    parser.add_argument("--max-new-tokens", type=int, default=256, help="Maximum tokens to generate per sample")
    parser.add_argument("--skip-warmup", action="store_true", help="Skip warmup inference (not recommended)")

    # Output arguments
    parser.add_argument("--output-dir", type=str, default="./inference_results", help="Directory to save inference results")

    args = parser.parse_args()

    # Load test dataset
    test_dataset = load_from_disk(args.test_dataset)

    if args.sample_indices.strip():
        sample_indices = [int(x.strip()) for x in args.sample_indices.split(",")]
    else:
        sample_indices = list(range(len(test_dataset)))
        print(f"📊 Using all {len(sample_indices)} samples")

    # Load model
    model, tokenizer = load_model(args.model_path, args.load_from_hf, args.base_model)

    # Run batch inference
    predictions, ground_truths, inference_times, vram_usage = run_inference_batch(
        model,
        tokenizer,
        test_dataset,
        args.prompt,
        sample_indices,
        args.max_new_tokens,
        skip_warmup=args.skip_warmup,
    )

    # Save results
    import os
    os.makedirs(args.output_dir, exist_ok=True)
    output_file = os.path.join(args.output_dir, "inference_results.json")

    results = {
        "prompt": args.prompt,
        "model_path": args.model_path,
        "sample_indices": sample_indices,
        "predictions": predictions,
        "ground_truths": ground_truths,
        "inference_times": inference_times,
        "vram_usage": vram_usage,
    }

    with open(output_file, "w") as f:
        json.dump(results, f, indent=4)

    print(f"\n💾 Results saved to: {output_file}")
